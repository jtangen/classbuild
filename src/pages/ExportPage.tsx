            <p
              role="status"
              aria-live="polite"
              className="cb-mono"
              style={{
                margin: '12px 0 0',
                fontSize: 12.5,
                letterSpacing: '0.04em',
                color: 'var(--cb-text-muted)',
              }}
            >
              {headerStatus}
            </p>
