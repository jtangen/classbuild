/** Lowercase ASCII slug for download names. Accents are folded first
 *  ("Économie" → "economie"); a title with no Latin letters at all (e.g.
 *  心理学) falls back to `fallback`, so a download never ends up named ".zip". */
function sanitizeFilename(text: string, fallback = 'untitled'): string {
  const slug = text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return slug || fallback;
}

/** Short index file shipped at the top of each class bundle so an instructor
 *  unzipping it sees exactly what's inside and how to use each file. Lists
 *  only files actually written (`has`), so a step that failed isn't claimed. */
function buildClassReadme(
  chapter: GeneratedChapter,
  courseTitle: string,
  chapterNum: number,
  has: (file: string) => boolean,
): string {
  const lines: string[] = [];
  const entry = (file: string, description: string) => {
    if (has(file)) lines.push(`${file.length < 26 ? file.padEnd(26) : `${file}  `}${description}`);
  };
  lines.push(`${courseTitle}`);
  lines.push(`Class ${String(chapterNum).padStart(2, '0')} — ${chapter.title}`);
  lines.push('='.repeat(64));
  lines.push('');
  lines.push('Generated by ClassBuild · classbuild.ai');
  lines.push('');
  lines.push('CONTENTS');
  lines.push('-'.repeat(64));
  entry('reading.html', 'The chapter reading, themed for offline viewing.');
  entry('practice-quiz.html', 'Self-paced practice quiz with feedback on every answer.');
  entry('practice-quiz.txt', 'Practice quiz source text (the interactive quiz could not be built).');
  entry('in-class-quiz-pack.zip', 'Five shuffled .docx versions + answer key.');
  entry('in-class-quiz.json', 'In-class quiz data (the .docx pack could not be built).');
  entry('weekly-challenge.html', 'Mastery challenge — open in a browser.');
  entry('weekly-challenge-scorm.zip', 'SCORM 2004 package — upload to Canvas / Moodle / Blackboard.');
  entry('weekly-challenge.json', 'Weekly challenge data (the challenge page could not be built).');
  entry('slides.pptx', 'Lecture deck, one rendered image per slide, with speaker notes.');
  entry('slides.json', 'Slide titles, image prompts and speaker notes (render the deck with an OpenAI key).');
  entry('audiobook.mp3', 'Class audiobook narrated through ElevenLabs.');
  entry('audio-transcript.txt', 'Plain-text transcript adapted for spoken delivery.');
  entry('teaching-pack.docx', 'Conversation starters + in-class activities + facilitation guides.');
  lines.push('');
  lines.push('Everything is offline — no internet needed to use any of the files.');
  return lines.join('\n');
}

/** README for the whole-course ZIP: every file actually written, grouped by
 *  class, plus anything that couldn't be included and why. */
function buildCourseReadme(
  courseTitle: string,
  sections: Array<{ heading: string; files: Array<[file: string, description: string]> }>,
  notes: string[],
): string {
  const width = Math.min(
    44,
    Math.max(26, ...sections.flatMap((s) => s.files.map(([file]) => file.length + 2))),
  );
  const lines: string[] = [
    courseTitle,
    '='.repeat(64),
    '',
    'Generated by ClassBuild · classbuild.ai',
    '',
    'CONTENTS',
    '-'.repeat(64),
  ];
  for (const section of sections) {
    if (section.files.length === 0) continue;
    lines.push('', section.heading);
    for (const [file, description] of section.files) {
      lines.push(`  ${file.length < width ? file.padEnd(width) : `${file}  `}${description}`);
    }
  }
  if (notes.length > 0) {
    lines.push('', 'NOT INCLUDED', '-'.repeat(64));
    for (const note of notes) lines.push(`- ${note}`);
  }
  lines.push('', 'Everything is offline — no internet needed to use any of the files.');
  return lines.join('\n');
}

/** Banner text for export notes: the first few, then a pointer to the README
 *  (a large course can collect one note per class). */
function summarizeNotes(notes: string[], inReadme: boolean): string {
  if (notes.length <= 3) return notes.join(' ');
  return `${notes.slice(0, 2).join(' ')} …and ${notes.length - 2} more${inReadme ? ' (listed in README.txt inside the ZIP)' : ''}.`;
}

/** JSZip progress callback that reports whole-percent steps to a status line
 *  (JSZip fires it for every chunk, far more often than worth re-rendering). */
function zipProgress(setStatus: (status: string) => void): (meta: { percent: number }) => void {
  let last = -1;
  return ({ percent }) => {
    const pct = Math.floor(percent);
    if (pct === last) return;
    last = pct;
    setStatus(`Building the ZIP · ${pct}%`);
  };
}

/** Message for a ZIP that failed to build — usually a course too big to hold
 *  in browser memory at once. */
function zipFailureMessage(err: unknown, fallback: string): string {
  const message = err instanceof Error ? err.message : String(err);
  if (err instanceof RangeError || /allocation|out of memory|too large|array buffer/i.test(message)) {
    return 'The ZIP was too large to build in this browser. Download classes one at a time with the class · zip buttons instead.';
  }
  return friendlyError(err, fallback);
}

/** Teaching-pack DOCX: conversation starters, activities and their expanded
 *  facilitation guides. One builder for the per-chip download and the class
 *  bundle, so the two can't drift apart. */
async function buildTeachingPackDocx(chapter: GeneratedChapter, courseTitle: string): Promise<Blob> {
  const discussions = chapter.discussionData || [];
  const activities = chapter.activityData || [];
  const details = chapter.activityDetails || {};

  const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType } = await import('docx');
  const children: InstanceType<typeof Paragraph>[] = [];

  // Title
  children.push(new Paragraph({
    children: [new TextRun({ text: `Teaching Resources — ${chapter.title}`, bold: true, size: 32 })],
    heading: HeadingLevel.HEADING_1,
    spacing: { after: 200 },
  }));
  children.push(new Paragraph({
    children: [new TextRun({ text: courseTitle, italics: true, color: '666666', size: 22 })],
    spacing: { after: 400 },
  }));

  // Discussion starters
  if (discussions.length > 0) {
    children.push(new Paragraph({
      children: [new TextRun({ text: 'Conversation Starters', bold: true, size: 28 })],
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 300, after: 200 },
    }));
    children.push(new Paragraph({
      children: [new TextRun({ text: 'Display these on a slide as students arrive.', italics: true, color: '888888', size: 20 })],
      spacing: { after: 200 },
    }));
    discussions.forEach((d, i) => {
      children.push(new Paragraph({
        children: [
          new TextRun({ text: `${i + 1}. `, bold: true, size: 22 }),
          new TextRun({ text: `[${d.hook}] `, bold: true, color: '8b5cf6', size: 22 }),
          new TextRun({ text: d.prompt, size: 22 }),
        ],
        spacing: { after: 150 },
      }));
    });
  }

  // Activities
  if (activities.length > 0) {
    children.push(new Paragraph({
      children: [new TextRun({ text: 'In-Class Activities', bold: true, size: 28 })],
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 400, after: 200 },
    }));
    activities.forEach((a, i) => {
      children.push(new Paragraph({
        children: [
          new TextRun({ text: `${a.title}`, bold: true, size: 24 }),
          new TextRun({ text: `  (${a.duration})`, color: '888888', size: 20 }),
        ],
        heading: HeadingLevel.HEADING_3,
        spacing: { before: 300, after: 100 },
      }));
      children.push(new Paragraph({
        children: [new TextRun({ text: a.description, size: 22 })],
        spacing: { after: 100 },
      }));
      children.push(new Paragraph({
        children: [
          new TextRun({ text: 'Materials: ', bold: true, size: 20 }),
          new TextRun({ text: a.materials, size: 20 }),
        ],
        spacing: { after: 50 },
      }));
      children.push(new Paragraph({
        children: [
          new TextRun({ text: 'Learning Goal: ', bold: true, size: 20 }),
          new TextRun({ text: a.learningGoal, size: 20 }),
        ],
        spacing: { after: 50 },
      }));
      children.push(new Paragraph({
        children: [
          new TextRun({ text: 'Scaling: ', bold: true, size: 20 }),
          new TextRun({ text: a.scalingNotes, size: 20 }),
        ],
        spacing: { after: 100 },
      }));

      // Expanded guide if available. Normalized: details persisted before the
      // parser normalized them can lack an array field.
      const detail = normalizeActivityDetail(details[i]);
      if (detail) {
        children.push(new Paragraph({
          children: [new TextRun({ text: 'Step-by-Step Guide', bold: true, size: 22, underline: {} })],
          spacing: { before: 150, after: 100 },
        }));
        detail.steps.forEach(s => {
          children.push(new Paragraph({
            children: [
              new TextRun({ text: `[${s.timing}] `, bold: true, size: 20 }),
              new TextRun({ text: s.instruction, size: 20 }),
            ],
            spacing: { after: 30 },
            indent: { left: 360 },
          }));
          if (s.studentAction) {
            children.push(new Paragraph({
              children: [new TextRun({ text: `Students: ${s.studentAction}`, italics: true, color: '666666', size: 18 })],
              indent: { left: 720 },
              spacing: { after: 80 },
            }));
          }
        });
        if (detail.facilitationTips.length > 0) {
          children.push(new Paragraph({
            children: [new TextRun({ text: 'Facilitation Tips', bold: true, size: 20 })],
            spacing: { before: 100, after: 50 },
          }));
          detail.facilitationTips.forEach(t => {
            children.push(new Paragraph({
              children: [new TextRun({ text: `• ${t}`, size: 20 })],
              indent: { left: 360 },
              spacing: { after: 30 },
            }));
          });
        }
        if (detail.commonPitfalls.length > 0) {
          children.push(new Paragraph({
            children: [new TextRun({ text: 'Common Pitfalls', bold: true, size: 20 })],
            spacing: { before: 100, after: 50 },
          }));
          detail.commonPitfalls.forEach(p => {
            children.push(new Paragraph({
              children: [new TextRun({ text: `• ${p}`, size: 20 })],
              indent: { left: 360 },
              spacing: { after: 30 },
            }));
          });
        }
        children.push(new Paragraph({
          children: [
            new TextRun({ text: 'Debrief: ', bold: true, size: 20 }),
            new TextRun({ text: detail.debriefGuide, size: 20 }),
          ],
          spacing: { before: 100, after: 100 },
        }));
      }
    });
  }

  // Footer
  children.push(new Paragraph({
    children: [new TextRun({ text: `Generated by ClassBuild`, italics: true, color: '999999', size: 18 })],
    alignment: AlignmentType.CENTER,
    spacing: { before: 600 },
  }));

  const doc = new Document({ sections: [{ children }] });
  return Packer.toBlob(doc);
}

/** Message for when the app-wide one-deck-at-a-time render lock is held. */
function deckBusyMessage(): string | null {
  const busy = useUiStore.getState().slidesRender;
  return busy
    ? `A slide deck (Class ${busy.chapterNum}) is still rendering. Wait for it to finish, then export again.`
    : null;
}

/** User-facing note for slides that fell back to plain title slides. */
function deckFallbackNote(chapterNum: number, failedSlides: number[], total: number): string {
  return `Class ${chapterNum}: ${failedSlides.length} of ${total} slide images couldn't be rendered and are plain title slides (slide ${failedSlides.map((i) => i + 1).join(', ')}). Export the deck again to retry just those.`;
}

/**
 * Render a chapter's deck to PPTX, holding the app-wide one-render-at-a-time
 * lock (uiStore.slidesRender) for the duration. Callers check the lock is
 * free first (deckBusyMessage) — this sets it synchronously, before any await.
 */
async function renderChapterDeck(
  chapterNum: number,
  chapterTitle: string,
  slides: SlideData[],
  courseTitle: string,
  themeId: string | undefined,
  openaiApiKey: string,
  setSlideImage: (chapterNum: number, slideIndex: number, dataUri: string) => void,
): Promise<{ blob: Blob; failedSlides: number[] }> {
  useUiStore.getState().setSlidesRender({
    chapterNum,
    current: 0,
    total: slides.length,
    phase: 'rendering',
  });
  try {
    const { generatePptx } = await import('../services/export/pptxExporter');
    const { blob, failedSlides } = await generatePptx(
      slides,
      courseTitle,
      chapterTitle,
      themeId,
      openaiApiKey,
      {
        imageQuality: 'high',
        imageSize: '3840x2160',
        onProgress: (current, total, phase) =>
          useUiStore.getState().setSlidesRender({ chapterNum, current, total, phase }),
        onSlideRendered: (i, dataUri) => setSlideImage(chapterNum, i, dataUri),
        preRendered: Object.fromEntries(
          slides
            .map((s, i) => (s.imageDataUri ? [i, s.imageDataUri] : null))
            .filter((x): x is [number, string] => x !== null),
        ),
      },
    );
    return { blob, failedSlides };
  } finally {
    useUiStore.getState().setSlidesRender(null);
  }
}

